//! Embeds the web UI assets produced by `scripts/build-ui.sh`.
//!
//! If `crates/calcraft-ui/dist/` (or `$CALCRAFT_UI_DIST`) contains the
//! assets, this generates `$OUT_DIR/assets.rs` with content-hashed file
//! names and sets `cfg(calcraft_ui_assets)`. Otherwise the crate builds
//! without them and serves a placeholder page, so `cargo build` and
//! `cargo test` work without a wasm toolchain. Set `CALCRAFT_UI_REQUIRED=1`
//! to turn missing assets into a build error (release builds, CI).

use std::{
    env,
    error::Error,
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
};

/// Files produced by the UI build: (file in dist, published stem,
/// extension, content type).
const FILES: [(&str, &str, &str, &str); 3] = [
    ("app.js", "app", "js", "text/javascript; charset=utf-8"),
    ("app_bg.wasm", "app", "wasm", "application/wasm"),
    ("style.css", "style", "css", "text/css; charset=utf-8"),
];

/// 64-bit FNV-1a. The hash only makes cached file names change with their
/// content; it does not need to be cryptographic.
fn fnv1a(data: &[u8]) -> u64 {
    data.iter().fold(0xcbf2_9ce4_8422_2325, |hash, byte| {
        (hash ^ u64::from(*byte)).wrapping_mul(0x0100_0000_01b3)
    })
}

fn hashed_name(stem: &str, ext: &str, data: &[u8]) -> String {
    format!("{stem}-{:016x}.{ext}", fnv1a(data))
}

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo::rustc-check-cfg=cfg(calcraft_ui_assets)");
    println!("cargo::rerun-if-env-changed=CALCRAFT_UI_DIST");
    println!("cargo::rerun-if-env-changed=CALCRAFT_UI_REQUIRED");

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    let ui_dir = manifest_dir.join("../calcraft-ui");
    let dist = env::var_os("CALCRAFT_UI_DIST")
        .map(PathBuf::from)
        .unwrap_or_else(|| ui_dir.join("dist"));
    let required = env::var("CALCRAFT_UI_REQUIRED").is_ok_and(|v| v == "1");

    let complete = FILES.iter().all(|(file, ..)| dist.join(file).is_file());
    if !complete {
        if required {
            return Err(format!(
                "CALCRAFT_UI_REQUIRED=1 but the web UI assets are missing in {}; run scripts/build-ui.sh",
                dist.display()
            )
            .into());
        }
        // Rebuild once the assets appear: watch the directory that will
        // contain them (an existing path, so Cargo does not rerun this
        // script on every build).
        let watch = if dist.exists() {
            dist.as_path()
        } else {
            dist.parent().filter(|p| p.exists()).unwrap_or(&ui_dir)
        };
        println!("cargo::rerun-if-changed={}", watch.display());
        return Ok(());
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR")?);
    let mut code = String::from("// Generated by build.rs from the web UI build.\n");
    code.push_str("pub static FILES: &[super::Asset] = &[\n");
    let mut names = Vec::new();
    for (file, stem, ext, content_type) in FILES {
        let path = dist.join(file);
        println!("cargo::rerun-if-changed={}", path.display());
        let data = fs::read(&path)?;
        let name = hashed_name(stem, ext, &data);
        let source = std::path::absolute(&path)?;
        add_asset(&mut code, &name, content_type, &source)?;
        names.push(name);
    }
    let [js, wasm, css] = <[String; 3]>::try_from(names).map_err(|_| "asset count")?;

    // Bootstrap module: loads the wasm-bindgen glue and the module under
    // their hashed names (an external file, inline scripts are blocked by
    // the CSP).
    let boot = format!(
        "import init from \"./{js}\";\n\
         init({{ module_or_path: new URL(\"./{wasm}\", import.meta.url) }}).catch((error) => {{\n\
         \x20   console.error(error);\n\
         \x20   const message = document.createElement(\"p\");\n\
         \x20   message.textContent = \"The web interface could not be started. It needs a browser with WebAssembly support.\";\n\
         \x20   document.body.append(message);\n\
         }});\n"
    );
    let boot_name = hashed_name("boot", "js", boot.as_bytes());
    let boot_path = out_dir.join("boot.js");
    fs::write(&boot_path, &boot)?;
    add_asset(
        &mut code,
        &boot_name,
        "text/javascript; charset=utf-8",
        &boot_path,
    )?;
    code.push_str("];\n");
    writeln!(code, "pub const STYLESHEET: &str = {css:?};")?;
    writeln!(code, "pub const SCRIPT: &str = {boot_name:?};")?;

    fs::write(out_dir.join("assets.rs"), code)?;
    println!("cargo::rustc-cfg=calcraft_ui_assets");
    Ok(())
}

fn add_asset(
    code: &mut String,
    name: &str,
    content_type: &str,
    source: &Path,
) -> Result<(), Box<dyn Error>> {
    let source = source.to_str().ok_or("asset path is not valid UTF-8")?;
    writeln!(
        code,
        "    super::Asset {{ name: {name:?}, content_type: {content_type:?}, body: include_bytes!({source:?}) }},"
    )?;
    Ok(())
}
